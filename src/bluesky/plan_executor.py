        warn_if_msg_args_or_kwargs(msg, obj.kickoff, msg.args, kwargs)
        ret = obj.kickoff(*msg.args, **kwargs)
        await current_run.kickoff(msg)

        self._add_status_to_group(obj=obj, status_object=ret, group=group, action="kickoff")

        return ret

