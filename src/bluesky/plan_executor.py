class RunEngineStateMachine(StateMachine):
    """

    Attributes
    ----------
    is_idle
        State machine is in its idle state
    is_running
        State machine is in its running state
    is_paused
        State machine is paused.
    """

    class States(Enum):
        """state.name = state.value"""

        IDLE = "idle"

        RUNNING = "running"

        PAUSING = "pausing"
        PAUSED = "paused"

        HALTING = "halting"
        STOPPING = "stopping"
        ABORTING = "aborting"

        SUSPENDING = "suspending"

        PANICKED = "panicked"

        @classmethod
        def states(cls):
            return [state.value for state in cls]

    class Meta:
        allow_empty = False
        initial_state = "idle"
        transitions = {
            # Notice that 'transitions' and 'named_transitions' have
            # opposite to <--> from structure.
            # from_state : [valid_to_states]
            "idle": ["running", "panicked"],
            "running": ["idle", "pausing", "halting", "stopping", "aborting", "suspending", "panicked"],
            "pausing": ["paused", "idle", "halting", "aborting", "panicked"],
            "suspending": ["running", "halting", "aborting", "panicked"],
            "paused": ["idle", "running", "halting", "stopping", "aborting", "panicked"],
            "halting": ["idle", "panicked"],
            "stopping": ["idle", "panicked"],
            "aborting": ["idle", "panicked"],
            "panicked": [],
        }
        named_checkers = [
            ("can_pause", "pausing"),
        ]


def announce_state_change(identity, hooks: "Hooks", old_value, value) -> None:
    """Log a state change, and tell the state hook about it.

    Split out of :meth:`LoggingPropertyMachine.__set__` so that a state change
    which does not go through the machine can be announced too, and announced
    identically: there is one definition of what an observer is told rather
    than two to drift apart. `RunEngine` uses that for its ``panicked`` state,
    which cannot go through the machine because the loop is wedged.

    ``identity`` is what the log record names as having changed state. It is
    passed rather than inferred because the state now belongs to a
    `PlanExecutor`, one per plan, while the thing a user recognises in their
    logs is the long-lived `RunEngine` driving them.
    """
    tags = {"old_state": old_value, "new_state": value, "RE": identity}

    state_logger.info("Change state on %r from %r -> %r", identity, old_value, value, extra=tags)
    if hooks.state_hook is not None:
        hooks.state_hook(value, old_value)


def announce_suspend() -> None:
    """Tell the user a suspension is starting.

    Called by whichever entry point was asked, before it hands the work to
    the loop, so that the message reaches the user when they asked rather
    than whenever the loop gets to it. The ways in are disjoint -- a
    `RunEngine` goes straight to its executor rather than by way of its
    session -- so this is said once per suspension.
    """
    print("Suspending....To get prompt hit Ctrl-C twice to pause.")
    print(f"Suspension occurred at {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}.")


def _panicked_state() -> ProxyString:
    """The value `RunEngine.state` reports once the engine has panicked.

    A panicked RunEngine is not described by its session's state machine --
    the panic belongs to the engine, whose loop thread is wedged. But callers
    ask a state for more than its text: `bluesky.suspenders` reads
    ``RE.state.is_running``. So report a ProxyString over a machine forced to
    'panicked', which answers every ``is_*`` correctly, rather than a bare str
    which answers none of them.
    """
    machine = RunEngineStateMachine()
    machine.set_("panicked")
    return ProxyString("panicked", machine)


class LoggingPropertyMachine(PropertyMachine):
    """A state machine that announces every transition.

    Expects the owning object to have an ``_on_state_change`` attribute that is
    ``None``, or a callable with signature ``f(new_value, old_value)``. One
    attribute rather than the ``log`` and ``state_hook`` pair this used to
    duck-type, so that whoever builds the owner decides what an announcement
    says -- see :func:`announce_state_change`.
    """

    def __init__(self, machine_type):
        super().__init__(machine_type)

    def __set__(self, obj, value):
        own = type(obj)
        old_value = self.__get__(obj, own)
        super().__set__(obj, value)
        value = self.__get__(obj, own)
        if getattr(obj, "_on_state_change", None) is not None:
            obj._on_state_change(value, old_value)


RunEngineMetadata = MutableMapping[str, typing.Any]


def default_scan_id_source(md: RunEngineMetadata) -> SyncOrAsync[int]:
    return md.get("scan_id", 0) + 1


def _default_event_loop() -> asyncio.AbstractEventLoop:
    """The loop to use when none was given: the one running right here.

    Deliberately does not fall back on the process-wide loop a `RunEngine`
    registers with ``set_bluesky_event_loop``. That global belongs to the
    prompt -- it is what ``autoawait`` and `call_in_bluesky_event_loop` are
    for -- and a session reaching for it would quietly bind a headless plan to
    whichever RunEngine happened to be constructed first. A `RunEngine` always
    passes its loop in explicitly, so nothing that had one loses it.
    """
    try:
        return asyncio.get_running_loop()
    except RuntimeError:
        raise RuntimeError(
            "No event loop to run plans on. Either construct this from a "
            "coroutine, so that there is a running loop to adopt, or pass "
            "one in as loop=."
        ) from None


def _called(plan):
    """A pre- or post-plan may be given as a generator function or an iterable."""
    return plan() if callable(plan) else plan


def _default_md_validator(md: RunEngineMetadata) -> None:
    if "sample" in md and not (hasattr(md["sample"], "keys") or isinstance(md["sample"], str)):
        raise ValueError(
            "You specified 'sample' metadata. We give this field special "
            "significance in order to make your data easily searchable. "
            "Therefore, you must make 'sample' a string or a  "
            "dictionary, like so: "
            "GOOD: sample='dirt' "
            "GOOD: sample={'color': 'red', 'number': 5} "
            "BAD: sample=[1, 2] "
        )


def _default_md_normalizer(md: RunEngineMetadata) -> RunEngineMetadata:
    return md


@dataclass(frozen=True)
class PlanEnvironment:
    """Everything a plan needs to know about where it is being run.

    A `PlanExecutor` is given one of these instead of the `PlanSession` that
    built it, so that it can be constructed and tested without a session, and
    so that it has no route back to one.

    Frozen on purpose. A plan's environment does not change under it: an
    executor is built for one plan, and what it was told at that moment is what
    that plan sees to the end. A `PlanSession` keeps its settings as ordinary
    attributes and builds one of these from them in `PlanSession.make_executor`,
    so changing a setting takes effect for the *next* plan and the session
    never holds a second copy of one to keep in step.

    Everything here is read by the executor while its plan runs. Settings it
    only consumes at construction -- ``preprocessors``, which wrap the plan
    once, and the ``rewindable`` default, which seeds a flag the plan then owns
    -- are arguments to `PlanExecutor` instead, so that this stays a
    description of the environment rather than a bag of constructor arguments.

    ``md`` is the exception that proves the rule. It is shared by reference, so
    its *contents* still change -- but the executor only ever reads it, and
    never writes to it at all. The per-run ``scan_id`` is computed by the
    session through ``next_scan_id``, which hands the value back rather than
    leaving the caller to read it out of ``md``: two executors may be running
    plans on one session at once, and each must use the id it was given rather
    than whatever the other has since stored.

    Attributes
    ----------
    loop
        The event loop plans are executed on.
    log
        Where the executor logs to.
    md
        Persistent metadata, read-only to the executor. Not necessarily a
        ``dict``: `bluesky.utils.PersistentDict` is a supported choice, so this
        must never be copied.
    next_scan_id
        Called by the executor as each run opens, and returns the ``scan_id``
        for that run. The session computes it, stores it in ``md`` as the
        starting point for the next one, and returns it; concurrent callers are
        serialised so that no two runs are given the same id.
    md_validator
        Raises to prevent a run starting.
    md_normalizer
        Like ``md_validator``, but returns the normalized metadata.
    run_bundler_cls
        The bundler used to compose documents for each open run.
    run_engine_cls
        What ``Msg('RE_class')`` reports. ``None`` means the executor answers
        for itself, which is what a headless caller wants.
    record_interruptions
        Whether interruptions are recorded into their own event stream.
    strict_pre_declare
        Whether streams must be declared before they are used.
    """

    loop: asyncio.AbstractEventLoop
    log: LoggerAdapter
    md: RunEngineMetadata
    next_scan_id: Callable[[], SyncOrAsync[int]]
    md_validator: Callable = _default_md_validator
    md_normalizer: Callable = _default_md_normalizer
    run_bundler_cls: type[RunBundler] = RunBundler
    run_engine_cls: type | None = None
    record_interruptions: bool = False
    strict_pre_declare: bool = False


@dataclass
class Hooks:
    """The places a plan's progress can be observed from.

    Mutable, and shared by reference with every executor a session builds --
    the opposite guarantee to `PlanEnvironment`. Setting ``RE.msg_hook`` while
    a plan is running must take effect on *that* plan, because these are
    debugging and display attachments rather than anything the plan's meaning
    depends on.

    Attributes
    ----------
    msg_hook
        Called with each `Msg` before it is processed. ``RE.msg_hook = print``
        is the usual debugging idiom.
    waiting_hook
        Called with the status objects a plan is waiting on, and with ``None``
        once there is nothing left to wait for. Drives progress bars.
    state_hook
        Called ``f(new_state, old_state)`` on every state change.
    on_pause
        Called with no arguments when an executor comes to rest paused. A
        `RunEngine` uses this to release the main thread; a headless caller has
        no thread to release and can leave it unset.
    """

    msg_hook: Callable | None = None
    waiting_hook: Callable | None = None
    state_hook: Callable | None = None
    on_pause: Callable[[], None] | None = None


class PlanSession:
    """The environment that plans are executed in.

    A session holds everything that outlives any single plan: the persistent
    metadata, the document routing, the suspenders and the hooks. It does not
    execute anything itself; a :class:`PlanExecutor` does that, and one session
    builds many, one per plan::

        executor = session.make_executor(my_plan())
        result = await executor.run()

    A `RunEngine` composes a session with the machinery needed to drive it
    from a terminal on the main thread, and uses that same pair of calls. A
    session needs no `RunEngine`, so it can also be used directly from code
    that is already running in an asyncio event loop, such as a headless data
    acquisition service.

    A session does not hold the executors it builds -- whoever asked for one
    owns it. That is what lets a headless caller run two plans at once against
    the same durable metadata and suspenders. A `RunEngine` drives exactly one,
    and enforces that itself, because a terminal has one main thread to block.

    Parameters
    ----------
    md : MutableMapping[str, Any], optional
        The default is a standard Python dictionary, but fancier objects can
        be used to store long-term history and persist it between sessions.
        Any object adhering to the MutableMapping Protocol will work.

    loop : asyncio event loop, optional
        The loop plans will be executed on. Defaults to the running loop, or
        to the loop a `RunEngine` has already established.

    preprocessors : list, optional
        Generator functions that take in a plan (generator instance) and
        modify its messages on the way out. Functions are composed in order:
        the preprocessors ``[f, g]`` are applied like ``f(g(plan))``.

    md_validator : callable, optional
        A function that raises and prevents starting a run if it deems the
        metadata to be invalid or incomplete.

    md_normalizer : callable, optional
        A function that, like ``md_validator``, raises to prevent starting a
        run, but which returns the normalized metadata if it succeeds.

    scan_id_source : callable, optional
        A (possibly async) function used to calculate ``scan_id``.

    log : logging.LoggerAdapter, optional
        Where this session and its executors log to.

    on_pause : callable, optional
        Called with no arguments when an executor reaches a paused resting
        state. A `RunEngine` uses this to release the main thread; a headless
        caller has no thread to release and can leave it unset.

    run_bundler_cls : type, optional
        The bundler used to compose documents for each open run. A
        `RunEngine` passes its own, so that overriding it on a `RunEngine`
        subclass keeps working.

    run_engine_cls : type, optional
        What ``Msg('RE_class')`` reports. A `RunEngine` passes its own class;
        without one the executor answers for itself.

    Attributes
    ----------
    dispatcher
        The `Dispatcher` documents are emitted through.

    hooks
        The `Hooks` record shared with every executor this session builds.

    suspenders
        Read-only collection of the durable
        `bluesky.suspenders.SuspenderBase` objects, which every executor this
        session builds is given. Suspenders installed from inside a plan
        belong to that plan's executor and are not here.

    permit
        The durable `Permit`. Withheld while a suspender installed here is
        tripped, and waited on by every plan this session runs.

    md
        Persistent metadata, surviving every plan. Not necessarily a ``dict``:
        `bluesky.utils.PersistentDict` is a supported choice, which is why it
        is never copied -- an executor is handed this very mapping to read.

    The rest are settings, read as `make_executor` builds each plan's
    `PlanEnvironment`, so that changing one affects the next plan and never the
    one already running: ``preprocessors``, ``md_validator``,
    ``md_normalizer``, ``run_bundler_cls``, ``run_engine_cls``,
    ``record_interruptions``, ``strict_pre_declare``, and ``rewindable`` --
    the last being only the *default*, since a running plan owns its own live
    value in `PlanExecutor.rewindable_flag`.
    """

    def __init__(
        self,
        md: RunEngineMetadata | None = None,
        *,
        loop: asyncio.AbstractEventLoop | None = None,
        preprocessors: list | None = None,
        md_validator: typing.Callable | None = None,
        md_normalizer: typing.Callable | None = None,
        scan_id_source: typing.Callable[[RunEngineMetadata], SyncOrAsync[int]] = default_scan_id_source,
        log: LoggerAdapter | None = None,
        on_pause: typing.Callable[[], None] | None = None,
        run_bundler_cls: type[RunBundler] = RunBundler,
        run_engine_cls: type | None = None,
    ):
        if loop is None:
            loop = _default_event_loop()
        self._loop = loop

        self.log = log if log is not None else ComposableLogAdapter(logger, {"RE": self})

        # Set up before the environment is built, because the environment is
        # where it then lives: one mapping, held in one place.
        if md is None:
            md = {}
        md.setdefault("versions", {})

        try:
            import ophyd

            md["versions"]["ophyd"] = ophyd.__version__
        except ImportError:
            self.log.debug("Failed to import ophyd.")

        try:
            import ophyd_async

            md["versions"]["ophyd_async"] = ophyd_async.__version__
        except ImportError:
            self.log.debug("Failed to import ophyd_async.")

        from ._version import __version__

        md["versions"]["bluesky"] = __version__
        md["versions"]["event_model"] = event_model.__version__

        self.scan_id_source = scan_id_source
        # Serialises scan id allocation. Computing the next id reads md and
        # writes it back with an await in between, so two executors opening a
        # run at the same moment would otherwise be handed the same number.
        self._scan_id_lock = asyncio.Lock()

        # The observation points, shared by reference with every executor this
        # session builds, so that setting one mid-plan takes effect on that
        # plan.
        self.hooks = Hooks(on_pause=on_pause)

        # Settings a plan is run under. Plain attributes, read when
        # `make_executor` builds the frozen `PlanEnvironment` it hands over,
        # so changing one here takes effect for the next plan and never for
        # the one already running. Held once, so nothing can drift out of
        # step with a copy of itself.
        self.md = md
        self.preprocessors = preprocessors if preprocessors is not None else []
        self.md_validator = md_validator if md_validator is not None else _default_md_validator
        self.md_normalizer = md_normalizer if md_normalizer is not None else _default_md_normalizer
        self.run_bundler_cls = run_bundler_cls
        self.run_engine_cls = run_engine_cls
        self.record_interruptions = False
        self.strict_pre_declare = False
        self.rewindable = True

        self._suspenders: set[typing.Any] = set()
        # The durable half of the suspension state. Suspenders installed here
        # write to this permit, and every executor this session builds waits
        # on it as well as on its own -- the same shape as the two dispatchers.
        self.permit = Permit("session", loop)

        # Commands the user has added or removed. Composed into each executor's
        # vocabulary as it is built, so that registrations survive the plan
        # that was running when they were made.
        self._registered_commands: dict[str, typing.Callable] = {}
        self._unregistered_commands: set[str] = set()

        # public dispatcher for callbacks
        self.dispatcher = Dispatcher()
        self.ignore_exceptions = False

    @property
    def loop(self) -> asyncio.AbstractEventLoop:
        """The event loop plans are executed on."""
        return self._loop

    @property
    def ignore_exceptions(self):
        return self.dispatcher.ignore_exceptions

    @ignore_exceptions.setter
    def ignore_exceptions(self, val):
        # Only this session's dispatcher: a running plan's own subscribers live
        # on its executor, which this session does not hold. A `RunEngine`
        # holds both and sets both, so that RE.ignore_callback_exceptions goes
        # on meaning one thing.
        self.dispatcher.ignore_exceptions = val

    async def _next_scan_id(self) -> int:
        """Compute the ``scan_id`` for a run that is opening, and return it.

        Given to each executor so that writing to ``md`` stays the session's
        job: an executor is handed metadata to read, not to own.

        The id is *returned* rather than left in ``md`` for the caller to read
        back, because two executors may be opening runs at the same time and
        each must use the one it was given. Storing it in ``md`` is what makes
        the default source count up, and is still done here, under a lock that
        holds across the ``await``.
        """
        async with self._scan_id_lock:
            scan_id = await maybe_await(self.scan_id_source(self.md))
            self.md["scan_id"] = scan_id
            return scan_id

    def _announce_state(self, value, old_value) -> None:
        """Say that the plan in progress changed state."""
        announce_state_change(self, self.hooks, old_value, value)

    @property
    def suspenders(self):
        """Read-only collection of installed suspenders."""
        return tuple(self._suspenders)

    # The hooks are one mutable record, shared with every executor, so that
    # setting one mid-plan takes effect on the plan already running.

    @property
    def msg_hook(self):
        return self.hooks.msg_hook

    @msg_hook.setter
    def msg_hook(self, value):
        self.hooks.msg_hook = value

    @property
    def state_hook(self):
        return self.hooks.state_hook

    @state_hook.setter
    def state_hook(self, value):
        self.hooks.state_hook = value

    @property
    def waiting_hook(self):
        return self.hooks.waiting_hook

    @waiting_hook.setter
    def waiting_hook(self, value):
        self.hooks.waiting_hook = value

    @property
    def on_pause(self):
        return self.hooks.on_pause

    @on_pause.setter
    def on_pause(self, value):
        self.hooks.on_pause = value

    def subscribe(self, func, name="all"):
        """Register a callback function to consume documents.

        See :meth:`RunEngine.subscribe`.
        """
        return self.dispatcher.subscribe(func, name)

    def unsubscribe(self, token):
        """Unregister a callback function by its integer ID."""
        return self.dispatcher.unsubscribe(token)

    def register_command(self, name, func):
        """Register a new Message command.

        The session remembers it, so that it survives being composed over a
        different set of built-ins when the next executor is built.

        Parameters
        ----------
        name : str
        func : callable
            This can be a function or a method. The signature is ``f(msg)``.
        """
        self._registered_commands[name] = func
        self._unregistered_commands.discard(name)

    def unregister_command(self, name):
        """Unregister a Message command.

        Parameters
        ----------
        name : str
        """
        # Raise KeyError for an unknown command, as deleting from the registry
        # directly used to.
        if name not in self.commands:
            raise KeyError(name)
        self._registered_commands.pop(name, None)
        self._unregistered_commands.add(name)

    @property
    def commands(self) -> dict[str, typing.Callable]:
        """The vocabulary the next plan will understand.

        Composed from `PlanExecutor`'s built-ins and whatever the user has
        registered here. The built-ins are reported as the plain functions they
        are defined as, since this session holds no executor to bind them to,
        and they are named and documented the same either way.
        """
        registry = PlanExecutor.unbound_default_commands()
        registry.update(self._registered_commands)
        for name in self._unregistered_commands:
            registry.pop(name, None)
        return registry

    def make_executor(self, plan, *, metadata=None, subs=None) -> "PlanExecutor":
        """Build an executor for ``plan``, and hand it to the caller.

        The caller owns what comes back; this session does not keep a
        reference. Everything durable is passed in here instead -- the
        metadata, the settings, the document dispatcher, the hooks and the
        suspenders -- so that more than one executor can be running against one
        session at a time, which is what a headless service wants. A
        `RunEngine` keeps exactly one, and is where "one plan at a time" is
        enforced.

        Building a new executor is also how the previous plan's state is
        cleared, including its subscriptions: those live on the executor's own
        dispatcher and are discarded with it.

        Parameters
        ----------
        plan : iterable of Msg
            The plan the new executor will run. Malformed plans raise here, on
            the calling thread.
        metadata : dict, optional
            Metadata for every run the plan opens.
        subs : callable, list, or dict, optional
            Subscriptions lasting only as long as this plan. Same forms as
            :meth:`RunEngine.__call__` accepts.

        """
        # Wait for any already-tripped suspenders before the plan starts.
        # A suspension proper cannot do this job: there is no checkpoint yet
        # to rewind to, so `request_suspend` would abort the plan instead of
        # holding it. Hence a prologue, in-band, ahead of the plan's own first
        # message. Belongs here rather than in a RunEngine, which is why
        # headless callers used to miss it entirely.
        # This plan's own permit, under the session's. A suspender the plan
        # installs holds up this plan; one installed on the session holds up
        # every plan it runs, and the chain is what makes those one mechanism.
        permit = Permit("plan", self._loop, parent=self.permit)
        prologue = None
        if not self.permit.granted:
            prologue = single_gen(Msg("wait_for", None, [permit.wait_granted]))

        return PlanExecutor(
            plan,
            # Built fresh for this plan, from the settings as they stand right
            # now. Frozen once handed over, so the plan cannot have its
            # environment changed under it, and never held by this session, so
            # there is no second copy of a setting to keep in step.
            PlanEnvironment(
                loop=self._loop,
                log=self.log,
                md=self.md,
                next_scan_id=self._next_scan_id,
                md_validator=self.md_validator,
                md_normalizer=self.md_normalizer,
                run_bundler_cls=self.run_bundler_cls,
                run_engine_cls=self.run_engine_cls,
                record_interruptions=self.record_interruptions,
                strict_pre_declare=self.strict_pre_declare,
            ),
            preprocessors=self.preprocessors,
            rewindable=self.rewindable,
            metadata=metadata,
            subs=subs,
            prologue=prologue,
            dispatcher=self.dispatcher,
            hooks=self.hooks,
            on_state_change=self._announce_state,
            commands=dict(self._registered_commands),
            without_commands=self._unregistered_commands,
            suspenders=self._suspenders,
            permit=permit,
        )

    def install_suspender(self, suspender):
        """Install a durable suspender, given to every executor built after it.

        Installing subscribes the suspender to its signal here and now, and it
        stays subscribed between plans: a suspender that only started watching
        when a plan started could not report that it was *already* tripped, and
        waiting for beam that is already down is what suspenders are for.

        It has no plan to suspend, and needs none: tripping withholds this
        session's permit, and whichever executors are running are waiting on
        that permit already. A suspender never learns what it is suspending.
        """
        self._suspenders.add(suspender)
        suspender.install(self.permit)

    def remove_suspender(self, suspender):
        """Uninstall a durable suspender."""
        if suspender in self._suspenders:
            suspender.remove()
        self._suspenders.discard(suspender)

    def clear_suspenders(self):
        """Uninstall all suspenders."""
        for suspender in self.suspenders:
            self.remove_suspender(suspender)


class PlanExecutor:
    """Executes one plan, which may contain any number of runs.

    An executor owns everything that belongs to the execution of a single
    plan: the stack of generators being worked off, the messages cached for
    rewinding, the devices seen and staged, and the status objects being
    waited on. It is built for a plan and discarded after it, so clearing
    those caches is a matter of building a new one.

    It lives on its session's event loop, and holds no locks and no threading
    primitives. A `RunEngine` marshals everything the main thread asks for
    onto the loop before it arrives here, and a sync ophyd ``Status`` object's
    done-callback is trampolined onto the loop by
    :meth:`_add_status_to_group`, so every method that touches this object's
    state runs on the loop.

    :meth:`emit` is the exception, and the only one: a sync ophyd signal fires
    its monitor callback on the device's own thread, and that reaches ``emit``
    directly. It touches no executor state, but it does mean a document can be
    given to subscribers off the loop. See its docstring.

    Prefer :meth:`PlanSession.make_executor` to constructing one directly: a
    session must know which executor is running, because that is how a
    suspender reaches the plan in progress.

    Parameters
    ----------
    plan : iterable of Msg
        The plan to execute. Taken here rather than by :meth:`run` so that an
        executor is structurally for one plan: there is no second plan to hand
        it. ``env``'s preprocessors are applied to it now, so a malformed plan
        raises on the calling thread rather than inside the task.
    env : PlanEnvironment
        Where the plan is being run: the loop, the logger, the metadata and the
        settings that compose each run.
    metadata : dict, optional
        Metadata for every run this plan opens.
    subs : callable, list, or dict, optional
        Subscriptions lasting only as long as this plan.
    prologue : iterable of Msg, optional
        Messages to work off before the plan itself. A session uses this to
        wait for already-tripped suspenders.
    dispatcher : Dispatcher, optional
        Subscribers that outlive this plan. Documents go to them before this
        plan's own, which is the order a single shared registry gave by
        construction.
    hooks : Hooks, optional
        The observation points. Shared with the session, and read live.
    on_state_change : callable, optional
        Called ``f(new_state, old_state)`` on every state change. Whoever built
        this executor supplies it, because announcing a state change means
        naming who changed state, and that is a `RunEngine` when there is one.
    commands : mapping, optional
        Extra `Msg` commands, composed over the built-ins. A session passes the
        ones a user registered, plus ``install_suspender`` and
        ``remove_suspender``, which only mean anything when there is a session
        to install into.
    without_commands : collection of str, optional
        Built-in commands to leave out.
    suspenders : collection, optional
        The durable suspenders covering this plan. Reported by
        :attr:`suspenders`; they withhold ``session_permit``, not this
        executor, so nothing here is pointed at them.
    session_permit : Permit, optional
        The durable permit. Held up by suspenders installed on the session, so
        one condition covers every plan that session is running.
    preprocessors : sequence of callable, optional
        Generator functions applied to the plan now, composed in order, so
        that ``[f, g]`` is applied as ``f(g(plan))``. Consumed here rather
        than kept: once the plan is wrapped there is nothing left to preprocess
        which is why this is an argument and not part of `PlanEnvironment`.
    rewindable : bool, optional
        The *starting* value of :attr:`rewindable_flag`, which the plan then
        owns and changes constantly -- see `bluesky.preprocessors`. An
        argument for the same reason: the default is read once, at
        construction, and the live value lives on this executor.
    """

    _state = LoggingPropertyMachine(RunEngineStateMachine)

    def __init__(
        self,
        plan,
        env: PlanEnvironment,
        *,
        metadata: dict | None = None,
        subs=None,
        prologue=None,
        dispatcher: "Dispatcher | None" = None,
        hooks: Hooks | None = None,
        on_state_change: Callable[[typing.Any, typing.Any], None] | None = None,
        commands: typing.Mapping[str, Callable] | None = None,
        without_commands: typing.Collection[str] = (),
        suspenders: typing.Collection[typing.Any] = (),
        permit: Permit | None = None,
        preprocessors: typing.Sequence[Callable] = (),
        rewindable: bool = True,
    ):
        self._env = env
        self._hooks = hooks if hooks is not None else Hooks()
        self._on_state_change = on_state_change
        self._parent_dispatcher = dispatcher

        # When cleared, run() will pause until it is set again.
        self._run_permit = asyncio.Event()
        self._run_permit.set()
        # When set, done callbacks from status objects belonging to this plan
        # stop reporting failures: the plan they belong to is over.
        self._pardon_failures = asyncio.Event()
        # run() may only be entered once. A finished executor is 'idle' again,
        # so its state cannot tell a spent one from a fresh one.
        self._spent = False

        # Reached for by name through RunEngine._task, which bluesky's own
        # tests use to cancel a plan (test_run_engine.py). Private because
        # cancelling the task behind a plan's back is not a supported way to
        # stop one -- halt() is -- and the forward exists so those call sites
        # keep working, not because they are a good idea.
        self._task: asyncio.Task | None = None  # the task running this plan
        self._plan_stack: deque[typing.Any] = deque()  # generators to work off of
        self._response_stack: deque[typing.Any] = deque()  # responses to send into them
        # Processed msgs, for rewinding. None once a 'clear_checkpoint' has
        # made this plan unrewindable, which is what `resumable` tests for.
        self._msg_cache: deque[typing.Any] | None = deque()

        # Whether messages may be replayed on a rewind. Seeded from the
        # session's default, then owned outright: plans toggle this constantly
        # -- every trigger_and_read on a non-rewind-safe device does -- so the
        # live value is plan state and must not outlive the plan.
        self._rewindable_flag: bool = rewindable

        # Materialise this executor's state machine while this is still the
        # only thread with a reference, so that no later read from another
        # thread can race the WeakKeyDictionary insertion. Every write after
        # this happens on the event loop, which is why it needs no lock.
        _ = self._state

        # Subscriptions that last only as long as this plan, in a dispatcher
        # of their own. Making the lifetime structural means teardown is
        # nothing more than dropping this executor, and it gives plan tokens a
        # namespace of their own, so a plan cannot unsubscribe a session
        # callback by guessing an integer.
        self.dispatcher = Dispatcher()
        # One setting, not two: RE.ignore_callback_exceptions is the session's,
        # and a plan's subscribers must not behave differently from the rest.
        if dispatcher is not None:
            self.dispatcher.ignore_exceptions = dispatcher.ignore_exceptions
        for name, funcs in normalize_subs_input(subs).items():
            for func in funcs:
                self.dispatcher.subscribe(func, name)

        # Reached for through RunEngine._run_bundlers by bluesky's own tests,
        # to inspect the runs a plan has open. Private because the bundler for
        # an open run is mid-composition: reading it says nothing stable, and
        # the documents it emits are the supported way to see a run.
        self._run_bundlers: dict[typing.Any, RunBundler] = {}  # open run -> bundler
        self._metadata_per_call: dict[typing.Any, typing.Any] = {}  # md for every run
        self.run_start_uids: list[typing.Any] = []  # RunStart uids generated
        self._run_tracing_spans: list[Span] = []  # open tracing spans

        # The durable suspenders this plan was given, reported so that
        # `RunEngine.suspenders` can show them. The session owns their
        # subscriptions and they write to the session permit, so this executor
        # holds them for reporting only and never points them at itself.
        self._durable_suspenders: set[typing.Any] = set(suspenders)
        # The ones a plan installs for itself, which this executor owns
        # outright, and which write to the permit just below.
        self._plan_suspenders: set[typing.Any] = set()

        # This plan's own permit, the counterpart of its own dispatcher: a
        # suspender a plan installs holds up that plan alone. The session's is
        # shared with every plan it is running.
        self.permit = permit if permit is not None else Permit("plan", env.loop)

        self._staged: set[typing.Any] = set()  # staged, not yet unstaged
        self._objs_seen: set[typing.Any] = set()  # every object seen in a Msg
        self._movable_objs_touched: set[typing.Any] = set()  # everything we 'set'
        self._groups: defaultdict[str, set[Callable[[], asyncio.Future]]] = defaultdict(set)
        self._status_objs: defaultdict[typing.Any, set[typing.Any]] = defaultdict(set)
        # Reached for through RunEngine._seen_wait_and_move_on_keys by
        # test_flyer.py, to assert nothing was left behind. Private because it
        # is bookkeeping for one command's warning, not a fact about the plan.
        self._seen_wait_and_move_on_keys: set[typing.Any] = set()

        # An exception instance or class, to be raised into the plan.
        self.exception: typing.Any = None
        self.interrupted: bool = False  # paused, aborted or failed
        self.exit_status: str = "success"  # optimistic default
        self.reason: str = ""  # reason for an abort
        self._deferred_pause_requested: bool = False  # pause at next 'checkpoint'

        # The vocabulary this plan understands, composed once. A plan's
        # meaning must not change under it, and nothing can change it from
        # inside: no Msg touches the registry, so registering a command takes
        # effect for the next plan.
        registry = self._default_commands()
        registry.update(commands or {})
        for name in without_commands:
            registry.pop(name, None)
        self.command_registry: dict[str, typing.Callable] = registry

        # Load the plan last, so that a preprocessor seeing a half-built
        # executor is not a thing that can happen.
        self._plan = plan  # this ref is just used for metadata introspection
        if metadata:
            self._metadata_per_call.update(metadata)
        gen = ensure_generator(plan)
        for wrapper_func in preprocessors:
            gen = wrapper_func(gen)
        self._plan_stack.append(gen)
        self._response_stack.append(None)
        if prologue is not None:
            self._plan_stack.append(prologue)
            self._response_stack.append(None)

    # The hooks are the session's; firing one, and checking whether it is set
    # at all, belongs to whoever has something to report -- which for all three
    # of these is the executor.

    def _call_msg_hook(self, msg) -> None:
        """Show a message to the msg hook, if one is set."""
        if self._hooks.msg_hook is not None:
            self._hooks.msg_hook(msg)

    def _call_waiting_hook(self, status_objs) -> None:
        """Tell the waiting hook what this plan is waiting for, if one is set.

        ``status_objs`` is None once there is nothing left to wait for.
        """
        if self._hooks.waiting_hook is not None:
            self._hooks.waiting_hook(status_objs)

    def _notify_paused(self) -> None:
        """Announce that this plan has reached a paused resting state."""
        if self._hooks.on_pause is not None:
            self._hooks.on_pause()

    async def _emit_async(self, name, doc) -> None:
        """`RunBundler` awaits this for documents a plan produces itself.

        Monitor callbacks fire on a device's thread and use `emit` directly,
        which is why there are two spellings of one thing.
        """
        self.emit(name, doc)

    def emit(self, name, doc) -> None:
        """Give a document to the session's subscribers, then to this plan's.

        The session goes first so that subscriptions outliving the plan see a
        document before the ones that arrived with it, which is the order a
        single shared registry gave by construction.

        May be called from a thread that is not the event loop's: a sync ophyd
        signal fires its monitor callback on the device's own thread, and that
        path reaches here. Subscribers are therefore invoked on whichever
        thread emitted, which is not always the loop.
        """
        if self._parent_dispatcher is not None:
            self._parent_dispatcher.process(name, doc)
        self.dispatcher.process(name, doc)

    @property
    def env(self) -> PlanEnvironment:
        """Where this plan is being executed."""
        return self._env

    @property
    def loop(self) -> asyncio.AbstractEventLoop:
        """The event loop this plan is executed on."""
        return self._env.loop

    @property
    def suspenders(self) -> frozenset[typing.Any]:
        """Every suspender that can suspend this plan.

        The durable ones this executor was built with, plus any the plan
        installed for itself.
        """
        return frozenset(self._durable_suspenders | self._plan_suspenders)

    def install_suspender(self, suspender) -> None:
        """Install a suspender for the duration of this plan only.

        This is what ``Msg('install_suspender', None, suspender)`` does. The
        executor owns it: when the plan ends it is removed and unsubscribed,
        unlike a suspender installed on the session, which outlives every plan.
        """
        self._plan_suspenders.add(suspender)
        suspender.install(self.permit)

    def remove_suspender(self, suspender) -> None:
        """Uninstall a suspender, whether this plan's or a durable one.

        A durable suspender is the session's to unsubscribe, so removing one
        here only stops it suspending this plan.
        """
        if suspender in self._plan_suspenders:
            suspender.remove()
        self._plan_suspenders.discard(suspender)
        # A durable one is the session's to unsubscribe; all this can do is
        # stop reporting it, and drop any reason it is holding against this
        # plan alone. Its reason on the session permit is not ours to grant.
        self._durable_suspenders.discard(suspender)
        self.permit.grant(suspender)

    def adopt_suspender(self, suspender) -> None:
        """Report ``suspender`` as covering this plan too, without owning it.

        For a durable suspender installed while this plan is already running.
        It writes to the session permit, which this plan is waiting on
        already, so this only makes it visible in :attr:`suspenders`.
        """
        self._durable_suspenders.add(suspender)

    def _release_suspenders(self) -> None:
        """Let go of every suspender this plan installed. Once, as it ends."""
        for suspender in list(self._plan_suspenders):
            self.remove_suspender(suspender)
        self._durable_suspenders.clear()

    async def _run_out_of_band(self, plan):
        """Work off a short message sequence outside the plan stack.

        A suspender's pre-plan runs when its condition fires, which may be
        while the plan is already suspended for another condition, or while it
        is paused. In both of those the run loop will not reach a message
        pushed onto the plan stack -- suspended, it is parked in a ``wait_for``;
        paused, it is parked on the run permit -- so a shutter that must close
        now cannot be closed by queueing a message.

        Only for the short, self-contained sequences a pre- or post-plan is.
        There is no plan stack, no checkpoint and no rewind here.
        """
        for msg in ensure_generator(_called(plan)):
            await self.commands[msg.command](msg)

    async def _supervise_permit(self, held_at_start=False):
        """Suspend this plan whenever permission to run is withheld.

        One suspension per episode, however many conditions are standing: that
        is not a rule enforced by a flag, it is where this loop is sitting. A
        condition tripping while the loop is inside an episode joins the wait
        rather than starting a second rewind, though it still runs its own
        pre-plan when it fires.

        ``held_at_start`` keeps this out of the way of the wait `make_executor`
        puts in front of the plan: a permit already withheld when the plan
        starts is being held there, and must not also be suspended here, where
        there is no checkpoint to rewind to. It is passed in rather than tested
        here because this task starts a turn of the loop later, and a condition
        going bad in that window is a real trip.
        """
        if held_at_start:
            await self.permit.wait_granted()
        while True:
            await self.permit.wait_withheld()
            suspension = self.permit.suspension
            if suspension is None:
                continue
            seen = dict(self.permit.reasons)
            first = next(iter(seen.values()))
            joined: list[Suspension] = []

            def unwind(joined=joined, first=first):
                # A generator function, so its body runs when the suspension
                # unwinds rather than when it starts -- by then `joined` holds
                # every condition that turned up while the plan was held, and
                # they are undone in the reverse of the order they arrived.
                for reason in reversed(joined):
                    if reason.post_plan is not None:
                        yield from ensure_generator(_called(reason.post_plan))
                if first.post_plan is not None:
                    yield from ensure_generator(_called(first.post_plan))

            announce_suspend()
            self.loop.create_task(  # noqa: RUF006
                self.request_suspend(
                    self.permit.wait_granted,
                    pre_plan=first.pre_plan,
                    post_plan=unwind,
                    justification=suspension.justification,
                )
            )
            await self._join_episode(seen, joined)

    async def _join_episode(self, seen, joined):
        """Run the pre-plan of every condition that joins a suspension.

        Each runs when its condition fires, out of band, because the plan is
        parked in the suspension's ``wait_for`` and will not reach anything
        pushed onto its stack. Their post-plans are not run here: they belong
        to the suspension's unwind, in band and in reverse, so that they
        cannot race the plan resuming.
        """
        while not self.permit.granted:
            await self.permit.wait_changed()
            for key, reason in self.permit.reasons.items():
                if key in seen:
                    continue
                seen[key] = reason
                joined.append(reason)
                if reason.pre_plan is not None:
                    await self._run_out_of_band(reason.pre_plan)

    @property
    def resumable(self) -> bool:
        "i.e., can the plan in progress be rewound"
        return self._msg_cache is not None

    @property
    def rewindable_flag(self) -> bool:
        """Whether messages may be replayed on a rewind.

        Owned by this executor and seeded from the session's default, because
        plans change it for their own duration -- see
        `bluesky.preprocessors.rewindable_wrapper`, which every
        ``trigger_and_read`` on a non-rewind-safe device goes through.
        """
        return self._rewindable_flag

    @rewindable_flag.setter
    def rewindable_flag(self, value: bool) -> None:
        # Changing this invalidates the message cache, because the point of
        # turning it off is that what follows must not be replayed. Both
        # writers -- Msg('rewindable') and RunEngine.rewindable -- come through
        # here, so there is one definition of what the change means.
        cur_state = self._rewindable_flag
        self._rewindable_flag = bool(value)
        if self.resumable and self._rewindable_flag != cur_state:
            self._reset_checkpoint_state()

    @property
    def deferred_pause_requested(self) -> bool:
        """Whether a deferred pause is waiting for the next checkpoint."""
        return self._deferred_pause_requested

    def permit_run(self) -> None:
        """Allow run() to proceed. Must be called on the event loop.

        Public because driving an executor is a caller's job: a `RunEngine`
        blocks the run before scheduling the task and permits it once the main
        thread is parked, and a headless driver needs the same pair.
        """
        self._run_permit.set()

    def block_run(self) -> None:
        """Hold run() at its next resting point. Must be called on the loop.

        The other half of :meth:`permit_run`.
        """
        self._run_permit.clear()

    def result(self, plan_return) -> RunEngineResult:
        """Describe how the plan finished."""
        return RunEngineResult(
            tuple(self.run_start_uids),
            plan_return,
            self.exit_status,
            self.interrupted,
            self.reason,
            self.exception,
        )

    @property
    def state(self):
        """This plan's state. One of {'idle', 'running', 'paused', ...}.

        Belongs to the executor rather than the session because every non-idle
        value describes one plan's execution: `pausing`, `suspending`,
        `aborting`, `stopping` and `halting` all mean that somebody outside the
        run loop has asked *this* plan to stop.
        """
        return self._state

    @state.setter
    def state(self, value):
        self._state = value

